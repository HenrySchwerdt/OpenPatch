#!/usr/bin/env python3
"""Tiny #ifdef/#else/#endif preprocessor for the Tamarin / ProVerif templates (*.in).

Tamarin's built-in preprocessor does not accept #ifdef inside `let` blocks or fact lists, and ProVerif has none,
so the variants are generated here. Usage: preprocess.py TEMPLATE OUTPUT [-DNAME ...]
Only whole lines that start with '#ifdef NAME', '#ifndef NAME', '#else', '#endif' are directives; nesting is supported.
"""
import sys


def main() -> int:
    args = sys.argv[1:]
    defs = {a[2:] for a in args if a.startswith("-D")}
    pos = [a for a in args if not a.startswith("-D")]
    if len(pos) != 2:
        print(__doc__)
        return 2
    src, dst = pos
    out, stack = [], []  # stack of (active_before, cond_value)
    active = True
    for line in open(src, encoding="utf-8"):
        s = line.strip()
        if s.startswith("#ifdef ") or s.startswith("#ifndef "):
            name = s.split()[1]
            val = (name in defs) if s.startswith("#ifdef") else (name not in defs)
            stack.append((active, val))
            active = active and val
        elif s == "#else":
            before, val = stack[-1]
            active = before and not val
        elif s == "#endif":
            active, _ = stack.pop()
        elif active:
            out.append(line)
    if stack:
        raise SystemExit("unterminated #ifdef in " + src)
    text = "GENERATED by security/formal/preprocess.py from %s with defines %s -- do not edit" % (
        src.split("/")[-1], sorted(defs) or "none")
    header = ("(* %s *)\n" % text) if dst.endswith(".pv") else ("// %s\n" % text)
    open(dst, "w", encoding="utf-8").write(header + "".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
