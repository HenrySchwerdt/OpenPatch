#!/usr/bin/env python3
"""Traceability matrix: hazard -> requirement (spec) -> risk control (HW/FW/APP/PROC)
-> diagnostic code -> verification (test / sim scenario / bench procedure).

OpenPatch is a TEST PROJECT (never worn, never used with insulin on a person). This tool supports
the regulatory evidence structure only.

Sources parsed from the repository (nothing is duplicated here):
  hazards      docs/02-safety.md (H1..H10) + docs/06-diagnostics.md (proposed H11..H13)
  requirements spec/design-parameters.md (sections), referenced by anchor from trace-links.csv
  codes        spec/diag-codes.csv if present (generated by the diagnostics work package),
               else the section 4 tables of docs/06-diagnostics.md
  links        regulatory/RISK/trace-links.csv (curated hazard -> requirement -> control -> verification)
  verification Rust/Swift test functions, sim scenario ids (mechanical/sim/REPORT.md),
               bench procedures B01..B24 (docs/06-diagnostics.md 6.3), docs/02-safety.md section 3 steps

Every reference is checked for existence (file, symbol, anchor). Exit code 1 on ERROR (a broken link or a
hazard without requirement / control / verification). GAP findings (planned items, codes without a test
tag, planned `diag_<code>` tests not written yet) do not fail unless --strict is given.

Usage:
  python3 regulatory/tools/trace.py                 # summary, exit code
  python3 regulatory/tools/trace.py --report regulatory/RISK/TRACE.md --json regulatory/RISK/trace.json
  python3 regulatory/tools/trace.py --strict        # GAPs fail too
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve()
ROOT = HERE.parents[2]

SPEC = "spec/design-parameters.md"
SAFETY = "docs/02-safety.md"
DIAG = "docs/06-diagnostics.md"
SIM = "mechanical/sim/REPORT.md"
LINKS = "regulatory/RISK/trace-links.csv"
DIAG_CSV = "spec/diag-codes.csv"
DIAG_TRACE = "docs/06-diagnostics-trace.md"


class Ctx:
    def __init__(self, root: Path):
        self.root = root
        self.errors: list[str] = []
        self.gaps: list[str] = []
        self._cache: dict[str, str] = {}

    def text(self, rel: str) -> str | None:
        if rel in self._cache:
            return self._cache[rel]
        p = self.root / rel
        if not p.is_file():
            return None
        t = p.read_text(encoding="utf-8", errors="replace")
        self._cache[rel] = t
        return t

    def err(self, msg: str):
        self.errors.append(msg)

    def gap(self, msg: str):
        self.gaps.append(msg)


# ----------------------------------------------------------------------------- hazards
def parse_hazards(c: Ctx) -> dict[str, str]:
    hz: dict[str, str] = {}
    t = c.text(SAFETY) or ""
    for m in re.finditer(r"^\|\s*(H\d+)\s*\|\s*\*\*(.+?)\*\*", t, re.M):
        hz[m.group(1)] = m.group(2).strip()
    d = c.text(DIAG) or ""
    # "**H11** undetected degradation ..., countered by"
    for m in re.finditer(r"\*\*(H1[1-9])\*\*\s+(.+?)(?:,\s*countered|[;.]\s|$)", d, re.M):
        hz.setdefault(m.group(1), m.group(2).strip()[:90] + " (proposed)")
    if not hz:
        c.err(f"no hazards found in {SAFETY}")
    return hz


# ----------------------------------------------------------------------------- requirements
def section_body(text: str, sec: str) -> str | None:
    """Body of '## <sec>.' ... up to the next '## ' heading (sec like '7' or '7a' or '1b')."""
    m = re.search(rf"^## {re.escape(sec)}[. ].*$", text, re.M)
    if not m:
        return None
    rest = text[m.end():]
    n = re.search(r"^## ", rest, re.M)
    return rest[: n.start()] if n else rest


def resolve_ref(c: Ctx, ref: str, spec_alias: bool = False) -> tuple[bool, str]:
    """path#substr or path#section#substr. Returns (ok, message)."""
    parts = ref.split("#")
    path = parts[0]
    if path == "spec":
        path = SPEC
    t = c.text(path)
    if t is None:
        return False, f"file not found: {path}"
    if len(parts) == 1:
        return True, path
    if len(parts) == 2:
        sub = parts[1]
        if sub and sub not in t:
            return False, f"text not found in {path}: '{sub}'"
        return True, path
    sec, sub = parts[1], "#".join(parts[2:])
    body = section_body(t, sec)
    if body is None:
        return False, f"section '{sec}' not found in {path}"
    if sub and sub not in body:
        return False, f"text not found in {path} section {sec}: '{sub}'"
    return True, path


# ----------------------------------------------------------------------------- diagnostic codes
CODE_RE = re.compile(r"^\|\s*`([0-9A-F]-[0-9A-F]{2}-[0-9A-F]{3})`\s*\|")


def parse_codes(c: Ctx) -> tuple[list[dict], str]:
    codes: list[dict] = []
    csv_text = c.text(DIAG_CSV)
    if csv_text is not None:
        rd = csv.DictReader(csv_text.splitlines())
        names = {k.lower().strip(): k for k in (rd.fieldnames or [])}

        def pick(row, *cands):
            for k in cands:
                if k in names:
                    return (row.get(names[k]) or "").strip()
            return ""

        for row in rd:
            code = pick(row, "code", "id")
            if not code:
                continue
            codes.append({
                "code": code.strip("`"),
                "name": pick(row, "name"),
                "sev": pick(row, "sev", "severity"),
                "haz": pick(row, "haz", "hazard", "hazards"),
                "test": pick(row, "test", "tests"),
            })
        if codes:
            return codes, DIAG_CSV
    t = c.text(DIAG) or ""
    for line in t.splitlines():
        m = CODE_RE.match(line)
        if not m:
            continue
        cells = [x.strip() for x in line.strip().strip("|").split(" | ")]
        if len(cells) < 9:
            c.gap(f"code row with unexpected column count: {m.group(1)}")
            continue
        codes.append({
            "code": m.group(1),
            "name": cells[1].strip("`"),
            "sev": cells[-5],
            "haz": cells[-3],
            "test": cells[-2],
        })
    if not codes:
        c.err(f"no diagnostic codes found ({DIAG_CSV} or {DIAG})")
    return codes, DIAG + " (section 4 tables)"


def haz_list(s: str) -> list[str]:
    return re.findall(r"H\d+", s)


# ----------------------------------------------------------------------------- verification refs
def bench_ids(c: Ctx) -> set[str]:
    t = c.text(DIAG) or ""
    return set(re.findall(r"^\|\s*(B\d\d)\s*\|", t, re.M))


def safety_steps(c: Ctx) -> set[str]:
    t = c.text(SAFETY) or ""
    body = section_body(t, "3") or ""
    steps = set(re.findall(r"^(\d+)\.\s", body, re.M))
    steps.add("4")  # section 4 (diagnostics and hardware independence) is referenced as bench02:4
    return steps


def sim_ids(c: Ctx) -> set[str]:
    t = c.text(SIM) or ""
    return set(re.findall(r"^\|\s*([0-9]\.[0-9]+(?:-[A-Z0-9-]+)?)\s*\|", t, re.M))


def check_verification(c: Ctx, tok: str, ctxs: dict) -> tuple[bool, str]:
    kind, _, rest = tok.partition(":")
    if kind in ("rust", "swift"):
        path, _, name = rest.partition("::")
        t = c.text(path)
        if t is None:
            return False, f"test file not found: {path}"
        pat = rf"\bfn\s+{re.escape(name)}\b" if kind == "rust" else rf"func\s+{re.escape(name)}\b"
        if not re.search(pat, t):
            return False, f"test '{name}' not found in {path}"
        return True, f"{Path(path).name}::{name}"
    if kind == "diff":
        return ((c.root / rest).exists(), rest) if (c.root / rest).exists() else (False, f"not found: {rest}")
    if kind == "sim":
        if rest in ctxs["sim"]:
            return True, f"sim {rest}"
        return False, f"sim scenario {rest} not in {SIM}"
    if kind == "bench":
        if rest in ctxs["bench"]:
            return True, f"bench {rest}"
        return False, f"bench procedure {rest} not in {DIAG} 6.3"
    if kind == "bench02":
        if rest in ctxs["steps"]:
            return True, f"02-safety {rest}"
        return False, f"{SAFETY} section 3 step {rest} not found"
    if kind == "doc":
        ok, msg = resolve_ref(c, rest)
        return ok, rest if ok else msg
    return False, f"unknown verification kind '{kind}' in '{tok}'"


# ----------------------------------------------------------------------------- main build
def build(c: Ctx) -> dict:
    hazards = parse_hazards(c)
    codes, code_src = parse_codes(c)
    bench = bench_ids(c)
    ctxs = {"bench": bench, "steps": safety_steps(c), "sim": sim_ids(c)}

    by_haz_codes: dict[str, list[dict]] = defaultdict(list)
    for cd in codes:
        hs = haz_list(cd["haz"])
        for h in hs:
            by_haz_codes[h].append(cd)
            if h not in hazards:
                c.err(f"code {cd['code']} references unknown hazard {h}")
        if not hs and "process" not in cd["haz"].lower():
            c.gap(f"code {cd['code']} has no hazard link")
        tags = cd["test"]
        if not tags.strip():
            c.gap(f"code {cd['code']} has no test tag")
        for b in re.findall(r"\bB(\d\d)\b", tags):
            if f"B{b}" not in bench:
                c.err(f"code {cd['code']} cites bench procedure B{b} which does not exist")

    # planned core fault-injection tests diag_<code> for codes tagged C
    rust_text = ""
    for p in (c.root / "firmware-rs").rglob("*.rs"):
        if "target" in p.parts:
            continue
        try:
            rust_text += p.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            pass
    c_tagged = [cd for cd in codes if re.search(r"\bC\b", cd["test"])]
    c_found = 0
    for cd in c_tagged:
        nm = "diag_" + cd["code"].lower().replace("-", "_")
        if re.search(rf"\bfn\s+{nm}\b", rust_text):
            c_found += 1
    if c_tagged and c_found < len(c_tagged):
        c.gap(f"{len(c_tagged) - c_found} of {len(c_tagged)} codes tagged C have no `diag_<code>` core test yet (planned, WP-1/WP-2)")

    # links
    rows: list[dict] = []
    lt = c.text(LINKS)
    if lt is None:
        c.err(f"links file missing: {LINKS}")
        lt = ""
    rd = csv.DictReader(lt.splitlines())
    req_ids: set[str] = set()
    ctl_ids: set[str] = set()
    ver_ids: set[str] = set()
    for i, row in enumerate(rd, start=2):
        h = row["hazard"].strip()
        where = f"{LINKS}:{i} ({h})"
        if h not in hazards:
            c.err(f"{where}: unknown hazard")
        ok, msg = resolve_ref(c, row["requirement"].strip())
        if not ok:
            c.err(f"{where}: requirement: {msg}")
        status = row["status"].strip() or "impl"
        cref = row["control"].strip()
        ok2, msg2 = resolve_ref(c, cref)
        if not ok2:
            (c.gap if status == "plan" else c.err)(f"{where}: control: {msg2}")
        vers = []
        for tok in [t for t in row["verification"].split(";") if t.strip()]:
            tok = tok.strip()
            okv, mv = check_verification(c, tok, ctxs)
            if not okv:
                c.err(f"{where}: verification: {mv}")
            vers.append({"ref": tok, "ok": okv})
            ver_ids.add(tok)
        req_ids.add(row["requirement"].strip())
        ctl_ids.add(f"{row['ctype']}|{cref}")
        rows.append({"hazard": h, "requirement": row["requirement"].strip(), "ctype": row["ctype"].strip(),
                     "control": cref, "status": status, "verification": vers, "note": (row.get("note") or "").strip()})

    # completeness per hazard
    per_h = {}
    for h in sorted(hazards, key=lambda x: int(x[1:])):
        hr = [r for r in rows if r["hazard"] == h]
        hc = by_haz_codes.get(h, [])
        per_h[h] = {
            "title": hazards[h],
            "reqs": sorted({r["requirement"] for r in hr}),
            "controls": [(r["ctype"], r["control"], r["status"]) for r in hr],
            "codes": [x["code"] for x in hc],
            "verifications": sorted({v["ref"] for r in hr for v in r["verification"]}),
            "notes": [r["note"] for r in hr if r["note"]],
        }
        if not per_h[h]["reqs"]:
            c.err(f"{h}: no requirement linked")
        if not per_h[h]["controls"]:
            c.err(f"{h}: no risk control linked")
        if not per_h[h]["verifications"]:
            c.err(f"{h}: no verification linked")
        if not hc:
            ct = {t for t, _, _ in per_h[h]["controls"]}
            if ct <= {"PROC", "APP"}:
                c.gap(f"{h}: no diagnostic code (process/app control only, by design)")
            else:
                c.gap(f"{h}: no diagnostic code references this hazard")
        if all(s == "plan" for _, _, s in per_h[h]["controls"]):
            c.gap(f"{h}: all controls are still planned (nothing implemented)")

    return {
        "hazards": hazards, "per_hazard": per_h, "codes": codes, "code_source": code_src,
        "rows": rows, "c_tagged": len(c_tagged), "c_found": c_found,
        "counts": {
            "hazards": len(hazards),
            "requirements": len(req_ids),
            "controls": len(ctl_ids),
            "codes": len(codes),
            "tests": len(ver_ids),
            "links": len(rows),
        },
        "diag_trace_exists": (c.root / DIAG_TRACE).exists(),
    }


# ----------------------------------------------------------------------------- report
def sev_counts(codes):
    d = defaultdict(int)
    for cd in codes:
        d[cd["sev"] or "?"] += 1
    return dict(d)


def render(c: Ctx, r: dict) -> str:
    n = r["counts"]
    o = []
    o.append("# Traceability matrix (generated)\n")
    o.append("> GENERATED by `python3 regulatory/tools/trace.py --report regulatory/RISK/TRACE.md`. Do not edit by hand.")
    o.append("> OpenPatch is a test project, never used with insulin on a person; this is evidence structure for a future legal manufacturer.\n")
    o.append("Chain: hazard (`docs/02-safety.md`, `docs/06-diagnostics.md`) -> requirement (`spec/design-parameters.md`) -> risk control (HW/FW/APP/PROC) -> diagnostic code -> verification (test, simulation scenario, bench procedure).\n")
    o.append("## Summary\n")
    o.append("| Item | Count |\n|---|---|")
    for k in ("hazards", "requirements", "controls", "codes", "tests", "links"):
        label = {"tests": "verification references (distinct tests / sim rows / bench procedures)",
                 "requirements": "requirements referenced (distinct spec anchors)",
                 "controls": "risk controls (distinct)",
                 "links": "hazard-control links (rows of trace-links.csv)",
                 "codes": f"diagnostic codes (source: {r['code_source']}); severity {sev_counts(r['codes'])}"}.get(k, k)
        o.append(f"| {label} | {n[k]} |")
    o.append(f"| ERRORS (broken links, hazards without requirement/control/verification) | {len(c.errors)} |")
    o.append(f"| GAPS (planned or not yet written; informational) | {len(c.gaps)} |\n")
    o.append(f"Codes tagged `C` (core fault-injection test `diag_<code>`): {r['c_tagged']}, written: {r['c_found']}. "
             f"Per-code matrix (code x hazard x test): see `{DIAG_TRACE}` when the diagnostics work package has generated it"
             f" (exists in this checkout: {'yes' if r['diag_trace_exists'] else 'no'}); it is not duplicated here.\n")
    o.append("Status legend: `impl` = the control exists in the repository and its target was found; `plan` = documented design, not built. "
             "**No verification has been executed on hardware** (nothing in the repo has run on a target, see `firmware-rs/docs/stubs.md`); host tests and simulations are design-stage evidence only.\n")
    o.append("## Matrix\n")
    o.append("| Hazard | Requirements (spec) | Risk controls | Diagnostic codes | Verification |")
    o.append("|---|---|---|---|---|")
    for h, d in r["per_hazard"].items():
        reqs = "<br>".join(f"`{x.replace('spec#', 'spec §', 1).replace('#', ' / ')}`" for x in d["reqs"]) or "**MISSING**"
        ctl = "<br>".join(f"{t}{' (plan)' if s == 'plan' else ''}: `{p.split('#')[0]}`" for t, p, s in dict.fromkeys(d["controls"])) or "**MISSING**"
        codes = d["codes"]
        cs = (f"{len(codes)}: " + ", ".join(f"`{x}`" for x in codes[:6]) + (" ..." if len(codes) > 6 else "")) if codes else "none"
        v = d["verifications"]
        kinds = defaultdict(list)
        for t in v:
            kinds[t.split(":")[0]].append(t.split(":", 1)[1].split("::")[-1] if "::" in t else t.split(":", 1)[1])
        vs = "<br>".join(f"{k} ({len(x)}): " + ", ".join(f"`{y}`" for y in x[:4]) + (" ..." if len(x) > 4 else "")
                         for k, x in kinds.items()) or "**MISSING**"
        o.append(f"| **{h}** {d['title'][:60]} | {reqs} | {ctl} | {cs} | {vs} |")
    o.append("\n## Per-hazard notes\n")
    for h, d in r["per_hazard"].items():
        if d["notes"]:
            o.append(f"- **{h}**: " + "; ".join(d["notes"]))
    o.append("\n## Missing links\n")
    o.append("### Errors (fail CI)\n")
    o += [f"- {e}" for e in c.errors] or ["- none"]
    o.append("\n### Gaps (informational; `--strict` makes them fail)\n")
    o += [f"- {g}" for g in c.gaps] or ["- none"]
    o.append("")
    return "\n".join(o)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT), help="repository root")
    ap.add_argument("--report", help="write markdown report to this path")
    ap.add_argument("--json", help="write machine-readable result to this path")
    ap.add_argument("--strict", action="store_true", help="GAP findings also fail")
    a = ap.parse_args(argv)
    c = Ctx(Path(a.root))
    r = build(c)
    n = r["counts"]
    print(f"hazards={n['hazards']} requirements={n['requirements']} controls={n['controls']} "
          f"codes={n['codes']} (source {r['code_source']}) tests={n['tests']} links={n['links']}")
    print(f"errors={len(c.errors)} gaps={len(c.gaps)}")
    for e in c.errors:
        print("ERROR:", e)
    for g in c.gaps:
        print("GAP:  ", g)
    if a.report:
        Path(a.report).write_text(render(c, r), encoding="utf-8")
        print("wrote", a.report)
    if a.json:
        Path(a.json).write_text(json.dumps({"counts": n, "errors": c.errors, "gaps": c.gaps,
                                            "per_hazard": r["per_hazard"]}, indent=1, default=list), encoding="utf-8")
        print("wrote", a.json)
    if c.errors or (a.strict and c.gaps):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
