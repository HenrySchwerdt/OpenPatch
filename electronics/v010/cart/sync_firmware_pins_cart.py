#!/usr/bin/env python3
"""Write firmware-rs/openpatch-bench/src/board/cart_v1.rs (feature `board-cart-v1`) from the cup board file cup_v4.rs + cart/pin_assign.json.

The cart board is the cup chip set with another HJ-840 GPIO assignment, so the board file is cup_v4.rs with the pin moves (`take()` lines
of the `cup_pins!` macro) and the doc table rows re-pointed, plus the cart header. Run after pinassign_cart.py / netlist_cart.py.
TEST PROJECT, water only."""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
SRC = os.path.join(ROOT, "firmware-rs", "openpatch-bench", "src", "board", "cup_v4.rs")
DST = os.path.join(ROOT, "firmware-rs", "openpatch-bench", "src", "board", "cart_v1.rs")
sys.path.insert(0, os.path.join(HERE, "..", "design"))
FIELD = {"aphase": "APHASE", "bphase": "BPHASE", "aenbl": "AENBL", "benbl": "BENBL", "chg_stat": "CHG_STAT", "oc_ok": "OC_OK", "latch_q": "LATCH_Q",
         "dock_n": "DOCK_N", "sup_ok": "SUP_OK", "led_r": "LED_R", "led_g": "LED_G", "led_b": "LED_B", "sup_rx": "SUP_TXD", "sup_tx": "SUP_RXD",
         "sup_boot0": "SUP_BOOT0", "sup_nrst": "SUP_NRST", "mot_fwd": "MOT_FWD", "button": "BTN_N", "i2c_scl": "I2C_SCL", "i2c_sda": "I2C_SDA",
         "arm_clk": "ARM_CLK", "mcu_en": "MCU_EN", "buz_a": "BUZ_A"}
HEADER = """//! Cart pump main board v1 (feature `board-cart-v1`, TEST PROJECT, bench only, water only): the cup pod v4 chip set (HJ-840, 2 x DRV8838,
//! STM32C011 supervisor, TPL5010 latch) on the 57.0 x 10.6 mm cart outline. Same nets, same interlock, other HJ-840 GPIO pads.
//! GENERATED by `electronics/v010/cart/sync_firmware_pins_cart.py` from `cup_v4.rs` and `electronics/v010/cart/pin_assign.json`: edit those.
//!
//! Cart differences: `DOCK_N` comes from the ADAPTER-LOCK hall on a pigtail (low = adapter locked, the cup's "docked"); an open pigtail
//! reads high (100 k pull-up RDK) = not locked. Netlist: `electronics/v010/cart/netlist_cart.json`.
//!
"""


def main() -> None:
    s = open(SRC).read()
    pa = json.load(open(os.path.join(HERE, "pin_assign.json")))
    src = open(os.path.join(HERE, "..", "design", "netlist_v4.py")).read()
    hj = eval(re.search(r"HJ_PIN = (\{.*?\})\n", src, re.S).group(1))
    used = set()
    for f, n in FIELD.items():
        q = hj[pa[n]]
        assert q not in used, q
        used.add(q)
        emb = "P%s_%s" % (q[1], q[3:].zfill(2))
        s, c = re.subn(r"(\n            %s: \$p\.)P\d_\d\d(\.into\(\),)" % f, r"\g<1>%s\2" % emb, s)
        assert c == 1, (f, c)
        s, c = re.subn(r"\n//! \| [A-H]\d +\| P\d\.\d\d \| `%s` *\|" % n, lambda m: "\n//! | %-3s | %s | `%s`%s|" % (pa[n], q, n, " " * max(1, 10 - len(n) - 1)), s)
        assert c == 1, (n, c)
    s = re.sub(r"^//! Cup pod v4 board.*?\n//! board is in this file, so a netlist change is a change here only.\n", HEADER, s, flags=re.S)
    s = s.replace("in: dock hall DRV5032FA, LOW = docked", "in: adapter-lock hall DRV5032FA (pigtail), LOW = adapter locked")
    s = re.sub(r"//! Source of truth:.*?unused\):\n", "//! Pad / nRF pin of the cart hand placement (`electronics/v010/cart/pin_assign.json`; row A, B2-B7 and P0.00 / P0.01 unused):\n", s, flags=re.S)
    s = s.replace('pub const BOARD_NAME: &str = "cup-v4";', 'pub const BOARD_NAME: &str = "cart-v1";')
    assert 'BOARD_NAME: &str = "cart-v1"' in s and "Cart pump main board" in s
    open(DST, "w").write(s)
    print("cart_v1.rs written")


if __name__ == "__main__":
    main()
