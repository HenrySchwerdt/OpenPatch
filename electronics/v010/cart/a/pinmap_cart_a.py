#!/usr/bin/env python3
"""HJ-840 pin map of the cart A board for the firmware (plain python3) -> cart/a/PINMAP-A.md + cart/a/cart_a_pins.json.

TEST PROJECT, water only. Firmware is not changed here: a board file `cart_a_v1.rs` (feature `board-cart-a-v1`) can be generated the same way
as B's `../sync_firmware_pins_cart.py` does for `cart_v1.rs`, from cup_v4.rs + this assignment. Compared with B every signal keeps its
function and polarity; only HJ-840 pads move (table "B pad"). DOCK_N on A = lock detector switch SW2 (closed = locked = LOW) instead of
B's pigtail hall: same polarity, but a mechanical contact: the firmware should keep its debounce count (hardware RC 0.9 ms / 10 ms)."""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
from netlist_cart import HJ_SIGNALS  # noqa: E402

USE = {"APHASE": "out: U7A DRV8838 PH, also supervisor input (PA1)", "BPHASE": "out: U7B DRV8838 PH, also supervisor input (PA13)",
       "AENBL": "out: bridge A enable (1 = driven, 0 = brake)", "BENBL": "out: bridge B enable",
       "CHG_STAT": "in: MCP73832 STAT, low = charging", "OC_OK": "in: TPS2553 FAULT, low = current limit active (100 k pull-up)",
       "LATCH_Q": "in: interlock latch readback", "DOCK_N": "in: adapter-lock detector switch SW2 via RLK, LOW = adapter locked (100 k pull-up RDK, 100 nF CLK to 3V3)",
       "SUP_OK": "in: supervisor healthy", "LED_R": "out, active low (RGB common anode on VBAT, 1 k)", "LED_G": "out, active low",
       "LED_B": "out, active low", "SUP_TXD": "in: UART RX from the supervisor", "SUP_RXD": "out: UART TX to the supervisor",
       "SUP_BOOT0": "out: supervisor BOOT0 strap (100 k pull-down)", "SUP_NRST": "io, OPEN DRAIN ONLY: pulls the supervisor NRST low",
       "MOT_FWD": "out: forward intent, HIGH = forward (pull-up: reset default = forward = blocked when not locked)",
       "BTN_N": "in: top button SW1, internal pull-up", "I2C_SCL": "TWIM: TMAG5273A1 U10 (0x35) on the board, 4.7 k pull-ups, 100 kHz",
       "I2C_SDA": "TWIM", "ARM_CLK": "out: rising edge sets the latch and arms the supervisor, 100 k pull-down",
       "MCU_EN": "out: hardware leg of the motor enable (AND3 U36), 100 k pull-down", "BUZ_A": "out: sounder NFET gate (100 k pull-down)"}
FIXED = [("E1", "P0.18", "NRST", "reset (UICR PSELRESET), TPL5010 RSTn"), ("H7", "P0.04", "VMOT_SENSE", "SAADC AIN2: motor supply after the load switch, 10 k / 10 k"),
         ("F1/G1/F2", "D+ / D- / VBUS", "USB_DP / USB_DM / VBUS_P", "USB (DFU, charging)"), ("C2/C3", "SWDIO / SWCLK", "SWDIO / SWDCLK", "pogo pads TPR1-4 (bottom)"),
         ("H2", "VDDH", "VBAT", "the cell through the reverse-polarity P-FET Q1")]


def main() -> None:
    pa = json.load(open(os.path.join(HERE, "pin_assign.json")))
    pb = json.load(open(os.path.join(HERE, "..", "pin_assign.json")))
    src = open(os.path.join(HERE, "..", "..", "design", "netlist_v4.py")).read()
    hj = eval(re.search(r"HJ_PIN = (\{.*?\})\n", src, re.S).group(1))
    assert sorted(pa) == sorted(HJ_SIGNALS)
    js = {s: {"pad": pa[s], "nrf": hj[pa[s]], "b_pad": pb[s], "b_nrf": hj[pb[s]]} for s in HJ_SIGNALS}
    json.dump(js, open(os.path.join(HERE, "cart_a_pins.json"), "w"), indent=1)
    with open(os.path.join(HERE, "PINMAP-A.md"), "w") as f:
        f.write("> TEST ONLY - NOT FOR HUMAN USE (see ../../../../DISCLAIMER.md). Bench only, water only.\n\n")
        f.write("# Cart A board: HJ-840 pin map for the firmware (generated by `pinmap_cart_a.py` from `pin_assign.json`)\n\n")
        f.write("Same signals, functions and polarities as B (`../README.md` \"HJ-840 pin assignment\"); only pads move. A board file for the\n"
                "firmware (`cart_a_v1.rs`, feature `board-cart-a-v1`) is generated like B's `cart_v1.rs` (`../sync_firmware_pins_cart.py`): not\n"
                "done here (firmware out of scope of the board work). Machine-readable: `cart_a_pins.json`.\n\n")
        f.write("| HJ-840 pad | nRF pin | Net | Use | B pad (B nRF) |\n|---|---|---|---|---|\n")
        for s in sorted(HJ_SIGNALS, key=lambda s: pa[s]):
            f.write("| %s | %s | `%s` | %s | %s (%s) |\n" % (pa[s], hj[pa[s]], s, USE[s], pb[s], hj[pb[s]]))
        for pad, pin, net, use in FIXED:
            f.write("| %s | %s | `%s` | %s | same |\n" % (pad, pin, net, use))
        f.write("\nUnused: row A (antenna; A1 GND, A7-A8 bridge), B2-B7, P0.00 / P0.01 (no 32 kHz crystal: LFRC), NFC pads.\n")
    print("PINMAP-A.md + cart_a_pins.json written,", len(pa), "signals,", sum(1 for s in pa if pa[s] != pb[s]), "moved vs B")


if __name__ == "__main__":
    main()
