#!/usr/bin/env python3
"""JLCPCB package of the CART board (plain python3 + kicad-cli): cart/jlc/ gerbers + drill zip, BOM, CPL (rotation corrected), NOT-ASSEMBLED.

usage: python3 export_cart_jlc.py [board.kicad_pcb [out dir]]   (default cart/cart.kicad_pcb -> cart/jlc)
Same rules as tools/export_cup_jlc.py after the cup pre-order review (H1-H3), table cart/jlc_rot_offsets.json (gen_cart_rot_offsets.py).
Rotation table: cart/jlc_rot_offsets.json, keyed by the ORDERED LCSC number, generated by cart/gen_cart_rot_offsets.py (pad-by-pad fit of
the official JLC/EasyEDA library footprint against ours): delta_ccw = orientation of the LCSC footprint relative to ours, origin_mm = where
the LCSC footprint origin lies in our footprint frame.
  * top side:    Rotation = KiCad rotation - delta
  * bottom side: Rotation = 180 - KiCad rotation - delta. CORRECTED 2026-11-25 (cart board): the cup review H3 rule "KiCad + delta" equals
    this only for KiCad rotations of 90 / 270 (the cup's U4A); for 0 / 180 it turns a bottom part by 180 degrees. Evidence: (1) verify_cpl.py
    places the official LCSC footprint at every CPL row (bottom = the top placement seen through the board) and compares every pad with our
    board: this rule fits every bottom part, H3 failed BZ1, QBA, U34, SW1 by 1.3-3.1 mm; (2) Bouni/kicad-jlcpcb-tools fabrication.py
    (_rotation_for_match / rotate): bottom = (180 - orientation) + correction, the same correction sign as on top.
  * Mid X / Mid Y = KiCad position moved to the LCSC origin (review H1: JU1 origin 5.08 mm behind our mouth origin)
Every placed part MUST have an entry (the export stops otherwise: a missing entry silently meant delta 0 before, review H2).
The per-part check table (written to cart/jlc/CPL-CHECK.md) lists every non-passive part for the 3D-preview check in ORDER.md."""
import csv
import json
import math
import os
import re
import shutil
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
CUP = HERE
K = os.environ.get("KICAD_CLI") or shutil.which("kicad-cli") or "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli"
PCB = sys.argv[1] if len(sys.argv) > 1 else os.path.join(CUP, "variants", "cart_clean.kicad_pcb")
PARTS = json.load(open(os.path.join(CUP, "parts.json")))
OFF = json.load(open(os.path.join(CUP, "jlc_rot_offsets.json")))
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(CUP, "jlc")
_NCU = 6 if '"In4.Cu"' in open(PCB).read() else 4
LAYERS = ",".join(["F.Cu"] + ["In%d.Cu" % k for k in range(1, _NCU - 1)] + ["B.Cu"]) + ",F.Paste,B.Paste,F.Silkscreen,B.Silkscreen,F.Mask,B.Mask,Edge.Cuts"


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        print("WARN", cmd[:5], r.stderr[-300:])
    return r


os.makedirs(OUT, exist_ok=True)
tmp = os.path.join(OUT, "_g")
shutil.rmtree(tmp, ignore_errors=True)
os.makedirs(tmp)
run([K, "pcb", "export", "gerbers", "--layers", LAYERS, "--subtract-soldermask", "-o", tmp + "/", PCB])
run([K, "pcb", "export", "drill", "--format", "excellon", "--excellon-units", "mm", "--excellon-separate-th", "--generate-map", "--map-format", "gerberx2", "-o", tmp + "/", PCB])
with zipfile.ZipFile(os.path.join(OUT, "openpatch-cart-gerbers.zip"), "w", zipfile.ZIP_DEFLATED) as zf:
    for f in sorted(os.listdir(tmp)):
        if not f.endswith((".gbrjob", ".rpt")) and "-drl_map" not in f:
            zf.write(os.path.join(tmp, f), f)
shutil.rmtree(tmp)

pos = os.path.join(OUT, "_pos.csv")
run([K, "pcb", "export", "pos", "--format", "csv", "--units", "mm", "--side", "both", "-o", pos, PCB])
rows = {r["Ref"]: r for r in csv.DictReader(open(pos))}
os.remove(pos)
bom, cpl, notasm, VAL, CHECK = {}, [], [], {}, []
for ref, p in PARTS.items():
    if ref not in rows:
        continue
    r = rows[ref]
    if p.get("dnp"):
        notasm.append((ref, p["value"], "DNP match part: " + (p.get("note") or "")))
        continue
    if not p.get("bom"):
        notasm.append((ref, p["value"], "bare pad / not assembled"))
        continue
    if not p.get("lcsc"):
        notasm.append((ref, p["value"], p.get("note") or "no LCSC part"))
        continue
    kr = float(r["Rot"])
    e = OFF.get(p["lcsc"])
    if e is None:
        raise SystemExit(f"{ref}: LCSC {p['lcsc']} has no entry in jlc_rot_offsets.json - run cart/gen_cart_rot_offsets.py")
    if e["fp"] != p["fp"]:
        raise SystemExit(f"{ref}: rotation entry measured on footprint {e['fp']}, the board uses {p['fp']}")
    top = r["Side"] == "top"
    delta = e["delta_ccw"]
    rot = ((kr - delta) if top else (180 - kr - delta)) % 360       # bottom: see the module docstring (cart verification 2026-11-25)
    tx, ty = e.get("origin_mm", [0.0, 0.0])
    x, y = float(r["PosX"]), float(r["PosY"])
    if math.hypot(tx, ty) > 0.1:      # below 0.1 mm the fit offset is land-pattern noise (e.g. C507223 0.05)
        if not top:
            raise SystemExit(f"{ref}: origin offset on a bottom-side part is not implemented")
        # local offset (y down) -> pos-file frame (y up), rotated counter-clockwise by the KiCad rotation
        c, s_ = math.cos(math.radians(kr)), math.sin(math.radians(kr))
        lx, ly = tx, -ty
        x, y = x + lx * c - ly * s_, y + lx * s_ + ly * c
    cpl.append([ref, f"{x:.4f}", f"{y:.4f}", "Top" if top else "Bottom", f"{rot:g}"])
    CHECK.append((ref, p["lcsc"], p["fp"], "Top" if top else "Bottom", kr, delta, rot, (x - float(r["PosX"]), y - float(r["PosY"])), e.get("maxdev_mm")))
    bom.setdefault((p["lcsc"], p["fp"]), []).append(ref)
    VAL.setdefault((p["lcsc"], p["fp"]), p["value"])
key = lambda s: (re.sub(r"\d", "", s), int(re.sub(r"\D", "", s) or 0))
with open(os.path.join(OUT, "BOM-jlcpcb.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["Comment", "Designator", "Footprint", "LCSC Part #"])
    for (lc, fp), refs in sorted(bom.items(), key=lambda x: key(sorted(x[1], key=key)[0])):
        w.writerow([VAL[(lc, fp)], ",".join(sorted(refs, key=key)), fp, lc])
with open(os.path.join(OUT, "CPL-jlcpcb.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["Designator", "Mid X", "Mid Y", "Layer", "Rotation"])
    w.writerows(cpl)
with open(os.path.join(OUT, "NOT-ASSEMBLED.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["Designator", "Value", "Reason"])
    w.writerows(notasm)
PASSIVE = ("R_", "C_", "L_")
with open(os.path.join(OUT, "CPL-CHECK.md"), "w") as f:
    f.write("# CPL rotation / origin check (generated by cart/export_cart_jlc.py)\n\n")
    f.write("Every placed part that is not a two-pad passive. delta = LCSC footprint orientation relative to ours (cart/gen_cart_rot_offsets.py, "
            "pad-by-pad on the ordered LCSC part); top: CPL = KiCad - delta, bottom: CPL = 180 - KiCad - delta (verified pad by pad: CPL-VERIFY.md). Check each row in the JLC 3D preview.\n\n")
    f.write("| Ref | LCSC | Footprint | Side | KiCad rot | delta | CPL rot | origin shift (mm) | pad fit (mm) |\n|---|---|---|---|---|---|---|---|---|\n")
    for ref, lc, fp, side, kr, d, rot, (dx, dy), dev in sorted(CHECK, key=lambda c: (c[3], key(c[0]))):
        if fp.startswith(PASSIVE):
            continue
        f.write(f"| {ref} | {lc} | {fp} | {side} | {kr:g} | {d} | **{rot:g}** | {dx:+.2f}, {dy:+.2f} | {dev} |\n")
print("JLC package:", len(cpl), "placements,", len(bom), "BOM lines,", len(notasm), "not assembled ->", OUT)
