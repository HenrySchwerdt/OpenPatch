#!/usr/bin/env python3
"""board.layout.json for the mechanical owner (KiCad python). Board frame: bx right, by up (viewed from the top/lid side); pod frame per size via params.json."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(ROOT, "..", "bench", "tools"))
import pcbnew
import benchlib as bl

PRM = json.load(open(os.path.join(ROOT, "board", "params.json")))
PARTS = json.load(open(os.path.join(ROOT, "board", "parts.json")))
b = pcbnew.LoadBoard(os.path.join(ROOT, "board", "v010.kicad_pcb"))
W, H = PRM["outline"]["w"], PRM["outline"]["h"]
HEIGHT = {"U1": 2.4, "BZ1": 3.0, "J1": 3.3, "SW1": 1.5, "U10T": 1.45, "U4A": 0.4, "U4B": 0.4, "SP1": 1.0, "SP2": 1.0, "L1": 1.8, "U7": 0.9, "U15": 1.1, "C21": 1.25, "Y1": 0.9}
DEFAULT_H = {"R": 0.4, "C": 0.55, "Q": 1.1, "U": 1.1, "D": 1.0, "L": 1.0, "T": 0.05, "P": 0.05, "H": 0.0, "J": 0.05, "S": 1.5}


def h_of(ref):
    return HEIGHT.get(ref, DEFAULT_H.get(ref[0], 1.0))


T = lambda v: pcbnew.ToMM(v)
comps = []
for f in b.GetFootprints():
    ref = f.GetReference()
    pos = f.GetPosition()
    bx, by = T(pos.x) - bl.OX, H - (T(pos.y) - bl.OY)
    bb = bl._box(f)
    side = "bottom" if f.GetSide() == pcbnew.B_Cu else "top"
    comps.append(dict(ref=ref, value=PARTS[ref]["value"], side=side, center_board_mm=[round(bx, 2), round(by, 2)],
                      courtyard_board_mm=[round(bb[0], 2), round(H - bb[3], 2), round(bb[2], 2), round(H - bb[1], 2)], height_mm=h_of(ref),
                      dnp=PARTS[ref].get("dnp", False)))
byref = {c["ref"]: c for c in comps}
over = []
zone_rect = {k: v["rect"] for k, v in PRM["zones"].items()}
for c in comps:
    x0, y0, x1, y1 = c["courtyard_board_mm"]
    for zn, lim in (("dock_insert_reserve", PRM["zones"]["dock_insert_reserve"]["bottom_max_h"]), ("battery_bay", PRM["zones"]["battery_bay"]["bottom_max_h"])):
        r = zone_rect[zn]
        if c["side"] == "bottom" and x0 < r[2] and x1 > r[0] and y0 < r[3] and y1 > r[1] and c["height_mm"] > lim and c["ref"] not in ("SP1", "SP2"):
            over.append((c["ref"], zn, c["height_mm"], lim))
    if c["side"] == "top" and c["height_mm"] > PRM["top_max_h"]:
        over.append((c["ref"], "top", c["height_mm"], PRM["top_max_h"]))
per_size = {}
for size, xr in PRM["x_r1"].items():
    ox = xr + PRM["pod_origin_offset_from_x_r1"]
    per_size[size] = dict(x_r1=xr, board_origin_in_pod_mm=[round(ox, 2), PRM["pod_origin_y"]], pod_length_mm=round(xr + 21.2 + PRM["tail_length_mm"], 1), pod_width_mm=32.0, pod_height_mm=8.5,
                          board_bottom_z_pod=5.3, board_top_z_pod=6.1)
rel = lambda n: byref[n]["center_board_mm"]
doc = dict(
    schema="openpatch-v010-layout/1",
    status="generated by tools/gen_layout.py from board/v010.kicad_pcb; PROPOSAL for the mechanical owner; outline and zones are parameters in board/params.json",
    units="mm",
    frame="board frame: bx right, by up, viewed from the TOP (lid side, F.Cu); KiCad y = H - by. x_pod = x_r1 + 2.6 + bx, y_pod = 1.5 + by, board bottom z 5.3, top z 6.1 (0.8 mm)",
    board=dict(thickness_mm=0.8, layers=4, stackup="JLC04081H-3313 class 4L 0.8 mm, ENIG", outline_rect=[0, 0, W, H], corner_r=PRM["outline"]["corner_r"],
               note="rectangle; the bench notches for snap-arm roots/screw bosses are NOT copied: the integrated shell is a new part (mechanical M2)"),
    per_size=per_size,
    zones=PRM["zones"],
    top_max_height_mm=PRM["top_max_h"],
    battery_bay=dict(rect_board_mm=zone_rect["battery_bay"], cell_mm=[15.0, 10.0, 3.2], spring_contacts=[dict(ref="SP1", net="VBAT", center=rel("SP1")), dict(ref="SP2", net="GND", center=rel("SP2"))],
                     z_cell_pod=[1.05, 4.25], note="Li-Po with PCM, tabs at the -x end; spring free height 1.0 mm vs 1.05 mm gap: VERIFY preload"),
    charge_pads=dict(window_in_lid=True, pads=[dict(ref="PAD1", net="CHG_PAD (+)", center=rel("PAD1"), size=[4.0, 3.0]), dict(ref="PAD2", net="GND (-)", center=rel("PAD2"), size=[4.0, 3.0])],
                     note="ENIG, top side z 6.1, window + gasket in the lid; cradle with 2 pogo pins"),
    connectors=dict(motor_picoblade=dict(ref="J1", side="bottom", center=rel("J1"), body_mm=[12.0, 6.9, 3.3], note="mating direction toward -x (rot 90 on the bottom side): VERIFY in the 3D check; motor lead about 32 mm from the motor pins (x_pod 15.9) - longer than the 25 mm of the architecture"),
                    swd_tc2030=dict(ref="J2", side="top", center=rel("J2"), note="Tag-Connect pads, flash before the lid is closed")),
    sensors=dict(tmag5273=dict(ref="U10T", side="bottom", center=rel("U10T"), z_sensing_pod=4.575, note="directly under the spindle magnet end face (bench layout HALL_3D: pod (30.2, 22.5), board bottom z 5.3); spindle magnet occupies x_pod <= 28.15"),
                 dock_halls=dict(refs=["U4A", "U4B"], side="bottom", centers=[rel("U4A"), rel("U4B")], note="2oo2 pair straddling the frozen dock hall position (bench: board (15.4, 9.7)); insert magnet d2 x 1, top face z 4.3")),
    other=dict(buzzer=dict(ref="BZ1", side="bottom", center=rel("BZ1"), body_mm=[8.5, 8.5, 3.0], note="sound port in the lid/floor needed"), e73=dict(ref="U1", side="bottom", center=rel("U1"), body_mm=[13, 18, 2.4], antenna_end="+x (board right edge)", keepout_rect_board_mm=zone_rect["antenna_keepout"]),
               button=dict(ref="SW1", side="top", center=rel("SW1"), height_mm=1.5), led=dict(ref="LD1", side="top", center=rel("LD1")),
               mounting_holes=[dict(ref=r, center=rel(r), d_mm=1.2, hole="NPTH") for r in ("H1", "H2", "H3")]),
    height_violations=over,
    components=comps,
)
json.dump(doc, open(os.path.join(ROOT, "board.layout.json"), "w"), indent=1)
print("components", len(comps), "height violations", over)
