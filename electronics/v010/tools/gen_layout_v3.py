#!/usr/bin/env python3
"""board.layout.json (schema /3) for the v3 split design: MAIN (ISP1807) / POWER / SENSOR (KiCad python)."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(ROOT, "..", "bench", "tools"))
import pcbnew
import benchlib as bl

HEIGHT = {"U1": 1.0, "SW1": 1.5, "U10T": 1.45, "U4A": 0.4, "U4B": 0.4, "SP1": 1.0, "SP2": 1.0, "MP1": 1.0, "MP2": 1.0, "MP3": 1.0, "MP4": 1.0, "PZ1": 1.0, "PZ2": 1.0,
          "L1": 1.8, "U7": 0.9, "U30": 0.6, "J3S": 2.0, "JU1": 3.3, "C21": 0.95, "C22": 0.95, "C7": 0.95, "C5": 0.95}
DEF = {"R": 0.25, "C": 0.3, "Q": 1.1, "U": 1.1, "D": 1.0, "L": 1.0, "T": 0.05, "H": 0.0, "J": 0.05, "S": 1.5, "P": 0.05}
doc = dict(schema="openpatch-v010-layout/3", status="generated by tools/gen_layout_v3.py from board/<name>/<name>.kicad_pcb (v3 split design with ISP1807, PROPOSAL for the mechanical owner)",
           units="mm", frame="per board: bx right, by up viewed from the TOP (lid side); KiCad y = H - by", boards={})
for name in ("main", "power", "sensor"):
    pcb = os.path.join(ROOT, "board", name, name + ".kicad_pcb")
    parts = json.load(open(os.path.join(ROOT, "board", name, "parts.json")))
    b = pcbnew.LoadBoard(pcb)
    bb0 = b.GetBoardEdgesBoundingBox()
    W = round(pcbnew.ToMM(bb0.GetWidth()), 2); H = round(pcbnew.ToMM(bb0.GetHeight()), 2)
    comps = []
    for f in b.GetFootprints():
        r = f.GetReference(); bb = bl._box(f)
        comps.append(dict(ref=r, value=parts[r]["value"], side="bottom" if f.GetSide() == pcbnew.B_Cu else "top",
                          center_board_mm=[round(pcbnew.ToMM(f.GetPosition().x) - bl.OX, 2), round(H - (pcbnew.ToMM(f.GetPosition().y) - bl.OY), 2)],
                          courtyard_board_mm=[round(bb[0], 2), round(H - bb[3], 2), round(bb[2], 2), round(H - bb[1], 2)], height_mm=HEIGHT.get(r, DEF.get(r[0], 1.0)),
                          dnp=parts[r].get("dnp", False)))
    top = max([c["height_mm"] for c in comps if c["side"] == "top"] or [0]); bot = max([c["height_mm"] for c in comps if c["side"] == "bottom"] or [0])
    doc["boards"][name] = dict(outline_rect=[0, 0, W, H], area_mm2=round(W * H, 1), layers=b.GetCopperLayerCount(), parts=len(comps), max_top_height_mm=top, max_bottom_height_mm=bot,
                               components=comps)
doc["interconnect"] = dict(
    main_power="J7 (MAIN, bottom) <-> J7P (POWER, top): 2 x 16 bare pads, 0.55 x 1.0 mm, 0.8 mm pitch, mirror patterns; elastomeric strip or spring contacts, mating method owned by mechanics",
    main_sensor="J3 (MAIN, bottom, 9 pads 0.5 x 1.2 @ 0.8) <-> J3S (SENSOR FH12-10S): OPEN (no <= 1 mm connector verified)",
    antenna="ISP1807 antenna half at the MAIN top edge (rect 0..9.7 x 0..4.5 mm from the top-left corner is copper-free on all layers)")
doc["notes"] = ["MAIN carries 6 spring pads on the bottom (cell 2 at the left, motor 4 at the right); positions are a proposal and must match the cell tabs and motor flex",
                "POWER: the USB-C receptacle is a placeholder (TYPE-C-31-M-12); the side tact SW1 is a proxy (TS-1187A)"]
json.dump(doc, open(os.path.join(ROOT, "board.layout.json"), "w"), indent=1)
print({k: (v["area_mm2"], v["layers"], v["parts"], v["max_top_height_mm"], v["max_bottom_height_mm"]) for k, v in doc["boards"].items()})
