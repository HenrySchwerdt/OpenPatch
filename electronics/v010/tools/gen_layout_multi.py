#!/usr/bin/env python3
"""board.layout.json for the split design: per board outline, area, heights, connector and key positions (KiCad python)."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(ROOT, "..", "bench", "tools"))
import pcbnew
import benchlib as bl

HEIGHT = {"U1": 2.4, "BZ1": 3.0, "J1": 3.3, "SW1": 1.5, "U10T": 1.45, "U4A": 0.4, "U4B": 0.4, "SP1": 1.0, "SP2": 1.0, "L1": 1.8, "U7": 0.9, "U30": 1.1,
          "J3": 2.0, "J7": 2.0, "J3S": 2.0, "J3U": 2.0, "JU1": 3.3, "C21": 1.25, "Y1": 0.9}
DEF = {"R": 0.4, "C": 0.55, "Q": 1.1, "U": 1.1, "D": 1.0, "L": 1.0, "T": 0.05, "H": 0.0, "J": 0.05, "S": 1.5, "P": 0.05}
CFG = {"main": (52.0, 38.0, 4), "sensor": (15.0, 13.0, 2), "usb": (22.0, 26.0, 2)}
doc = dict(schema="openpatch-v010-layout/2", status="generated by tools/gen_layout_multi.py from board/<name>/<name>.kicad_pcb (split design, PROPOSAL for the mechanical owner)",
           units="mm", frame="per board: bx right, by up viewed from the TOP (lid side); KiCad y = H - by", thickness_mm=0.8, boards={})
for name, (W, H, layers) in CFG.items():
    pcb = os.path.join(ROOT, "board", name, name + ".kicad_pcb")
    parts = json.load(open(os.path.join(ROOT, "board", name, "parts.json")))
    b = pcbnew.LoadBoard(pcb)
    comps = []
    for f in b.GetFootprints():
        r = f.GetReference()
        bb = bl._box(f)
        comps.append(dict(ref=r, value=parts[r]["value"], side="bottom" if f.GetSide() == pcbnew.B_Cu else "top",
                          center_board_mm=[round(pcbnew.ToMM(f.GetPosition().x) - bl.OX, 2), round(H - (pcbnew.ToMM(f.GetPosition().y) - bl.OY), 2)],
                          courtyard_board_mm=[round(bb[0], 2), round(H - bb[3], 2), round(bb[2], 2), round(H - bb[1], 2)], height_mm=HEIGHT.get(r, DEF.get(r[0], 1.0)),
                          dnp=parts[r].get("dnp", False)))
    top_max = max([c["height_mm"] for c in comps if c["side"] == "top"] or [0])
    bot_max = max([c["height_mm"] for c in comps if c["side"] == "bottom"] or [0])
    doc["boards"][name] = dict(outline_rect=[0, 0, W, H], area_mm2=round(W * H), layers=layers, corner_r=2.0 if name == "main" else 1.0, parts=len(comps),
                               max_top_height_mm=top_max, max_bottom_height_mm=bot_max,
                               ffc_connectors=[c["ref"] for c in comps if c["ref"].startswith("J3") or c["ref"] == "J7"], components=comps)
doc["interconnect"] = dict(
    main_sensor=dict(connectors="J3 (MAIN) <-> J3S (SENSOR), FH12-10S-0.5SH, 9 used", pins={"1": "GND", "2": "3V3", "3": "I2C_SDA", "4": "I2C_SCL", "5": "DOCK_N", "6": "DOCK_NB", "7": "TMAG_INT", "8": "GND", "9": "GND"}),
    main_usb=dict(connectors="J7 (MAIN) <-> J3U (USB), FH12-10S-0.5SH, 6 used", pins={"1": "VBUS_P", "2": "GND", "3": "USB_DP", "4": "USB_DM", "5": "GND", "6": "VBUS_P"}),
    note="FH12-10S is 2.0 mm tall (CAD note): a <= 1.0 mm FFC connector or spring contacts is an open point; cables inserted without soldering")
doc["notes"] = ["MAIN carries the E73 (13 x 18 x 2.4, bottom), buzzer MLT-8530 (3.0), PicoBlade (3.3), spring contacts for the cell: MAIN does NOT meet the 3 mm stack above the dock tunnel; it is the orderable/debuggable reference build",
                "SENSOR: TMAG5273 (bottom, 1.45) must sit at pod (30.2, 22.5) under the spindle magnet, one dock hall pair at the dock hall position (pod (43.8, 11.2)): the 15 x 13 outline is a placeholder, the FFC allows two separate sensor boards if needed",
                "USB board: the receptacle is a placeholder (TYPE-C-31-M-12); the IPX7 receptacle needs vendor confirmation"]
json.dump(doc, open(os.path.join(ROOT, "board.layout.json"), "w"), indent=1)
print({k: (v["area_mm2"], v["parts"], v["max_top_height_mm"], v["max_bottom_height_mm"]) for k, v in doc["boards"].items()})
